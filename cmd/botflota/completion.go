package main

import (
	"flag"
	"fmt"
	"os"
	"strings"
)

// helpFlagUsage restates -h in the help's words: every command answers help
// but no FlagSet defines it, so a generated script takes it from here.
const helpFlagUsage = "show this help and exit"

type completionCmd struct {
	fs *flag.FlagSet
}

func newCompletionCmd() *completionCmd {
	fs := flag.NewFlagSet("completion", flag.ContinueOnError)
	fs.Usage = func() {}
	return &completionCmd{fs: fs}
}

func runCompletion(args []string) int {
	cmd := newCompletionCmd()
	if code := parseArgs(cmd.fs, args); code >= 0 {
		return code
	}
	if cmd.fs.NArg() != 1 {
		fmt.Fprintf(os.Stderr, "completion needs one shell: %s\n\n",
			strings.Join(completionShells(), ", "))
		printHelp(os.Stderr, "completion")
		return 2
	}
	shell := cmd.fs.Arg(0)
	script, ok := completionScript(shell)
	if !ok {
		fmt.Fprintf(os.Stderr, "unknown shell %q: want %s\n\n",
			shell, strings.Join(completionShells(), ", "))
		printHelp(os.Stderr, "completion")
		return 2
	}
	fmt.Print(script)
	return 0
}

// completionShells names the shells a script exists for. It returns a fresh
// slice so the list is never shared package state.
func completionShells() []string {
	return []string{"bash", "zsh", "fish"}
}

// completionScript renders one shell's script by walking the CLI tree. The
// tree, not a list kept beside it, is the only source of commands and flags,
// so a new command cannot leave the completions stale.
func completionScript(shell string) (string, bool) {
	node := cliTree()
	var b strings.Builder
	switch shell {
	case "bash":
		writeBashCompletion(&b, node)
	case "zsh":
		writeZshCompletion(&b, node)
	case "fish":
		writeFishCompletion(&b, node)
	default:
		return "", false
	}
	return b.String(), true
}

// walkCommands visits every node with the path of names that reaches it.
func walkCommands(node *commandHelp, path []string, visit func(*commandHelp, []string)) {
	visit(node, path)
	for i := range node.sub {
		child := &node.sub[i]
		walkCommands(child, append(append([]string{}, path...), child.name), visit)
	}
}

// casePath is the key a generated case matches: the command words between
// spaces, so " config init " can only match that exact path.
func casePath(path []string) string {
	if len(path) == 0 {
		return " "
	}
	return " " + strings.Join(path, " ") + " "
}

// completionWords returns what a node offers: its subcommands, its own flags,
// and help, which every node answers.
func completionWords(node *commandHelp) []string {
	words := make([]string, 0, len(node.sub)+4)
	for i := range node.sub {
		words = append(words, node.sub[i].name)
	}
	return append(append(words, flagWords(node)...), "-h", "--help")
}

// flagWords reads the node's own FlagSet, the source help renders too, so a
// flag cannot appear in one and not the other.
func flagWords(node *commandHelp) []string {
	var words []string
	for _, f := range flagsOf(node) {
		if len(f.Name) == 1 {
			words = append(words, "-"+f.Name)
		} else {
			words = append(words, "--"+f.Name)
		}
	}
	return words
}

// flagsOf reads the node's own FlagSet, in the order help lists it.
func flagsOf(node *commandHelp) []*flag.Flag {
	if node.flags == nil {
		return nil
	}
	var flags []*flag.Flag
	node.flags().VisitAll(func(f *flag.Flag) { flags = append(flags, f) })
	return flags
}

func writeBashCompletion(b *strings.Builder, root *commandHelp) {
	b.WriteString("# bash completion for botflota; generated by \"botflota completion bash\".\n")
	b.WriteString("# Change the CLI tree in cmd/botflota/tree.go, never this file.\n")
	b.WriteString("_botflota_complete() {\n")
	b.WriteString("    local cur=$2\n")
	b.WriteString("    local path=\" \"\n")
	b.WriteString("    local i=1\n")
	b.WriteString("    while [ \"$i\" -lt \"$COMP_CWORD\" ]; do\n")
	b.WriteString("        case ${COMP_WORDS[i]} in\n")
	b.WriteString("            -*) ;;\n")
	b.WriteString("            *) path=\"$path${COMP_WORDS[i]} \" ;;\n")
	b.WriteString("        esac\n")
	b.WriteString("        i=$((i + 1))\n")
	b.WriteString("    done\n")
	b.WriteString("    case \"$path\" in\n")
	walkCommands(root, nil, func(node *commandHelp, path []string) {
		words := strings.Join(completionWords(node), " ")
		fmt.Fprintf(b, "        %q ) COMPREPLY=( $(compgen -W %q -- %q) ) ;;\n",
			casePath(path), words, "$cur")
	})
	b.WriteString("    esac\n")
	b.WriteString("}\n")
	b.WriteString("complete -F _botflota_complete botflota\n")
}

func writeZshCompletion(b *strings.Builder, root *commandHelp) {
	b.WriteString("#compdef botflota\n")
	b.WriteString("# zsh completion for botflota; generated by \"botflota completion zsh\".\n")
	b.WriteString("# Change the CLI tree in cmd/botflota/tree.go, never this file.\n")
	b.WriteString("_botflota() {\n")
	b.WriteString("  local path=\" \" word\n")
	b.WriteString("  local i=2\n")
	b.WriteString("  while (( i < CURRENT )); do\n")
	b.WriteString("    word=$words[i]\n")
	b.WriteString("    case $word in\n")
	b.WriteString("      -*) ;;\n")
	b.WriteString("      *) path=\"$path$word \" ;;\n")
	b.WriteString("    esac\n")
	b.WriteString("    (( i++ ))\n")
	b.WriteString("  done\n")
	b.WriteString("  case \"$path\" in\n")
	walkCommands(root, nil, func(node *commandHelp, path []string) {
		words := strings.Join(completionWords(node), " ")
		fmt.Fprintf(b, "    %q ) compadd -- %s ;;\n", casePath(path), words)
	})
	b.WriteString("  esac\n")
	b.WriteString("}\n")
	// The guard lets one script serve both uses: zsh autoloads the file as the
	// function body, where calling it again would recurse, while a sourced
	// file still has to register the function.
	b.WriteString("if [ \"$funcstack[1]\" = \"_botflota\" ]; then\n")
	b.WriteString("    _botflota \"$@\"\n")
	b.WriteString("else\n")
	b.WriteString("    compdef _botflota botflota\n")
	b.WriteString("fi\n")
}

// fishPathHelper is the preamble: a fish rule matches on the command path, so
// the helper prints the words already typed with flags removed.
const fishPathHelper = `function __botflota_path
    set -l words (commandline -opc)
    set -e words[1]
    for word in $words
        string match -q -- '-*' $word
        or echo $word
    end
end

function __botflota_at
    set -l path (__botflota_path)
    test (count $path) -eq (count $argv)
    and test (string join ' ' $path) = (string join ' ' $argv)
end
`

func writeFishCompletion(b *strings.Builder, root *commandHelp) {
	b.WriteString("# fish completion for botflota; generated by \"botflota completion fish\".\n")
	b.WriteString("# Change the CLI tree in cmd/botflota/tree.go, never this file.\n")
	b.WriteString(fishPathHelper)
	b.WriteString("\n")
	walkCommands(root, nil, func(node *commandHelp, path []string) {
		at := strings.TrimSpace("__botflota_at " + strings.Join(path, " "))
		condition := quoteFish(at)
		for i := range node.sub {
			child := &node.sub[i]
			fmt.Fprintf(b, "complete -c botflota -f -n %s -a %s -d %s\n",
				condition, quoteFish(child.name), quoteFish(child.summary))
		}
		for _, f := range flagsOf(node) {
			_, usage := flag.UnquoteUsage(f)
			fmt.Fprintf(b, "complete -c botflota -f -n %s %s -d %s\n",
				condition, fishFlag(f), quoteFish(usage))
		}
		fmt.Fprintf(b, "complete -c botflota -f -n %s -s h -l help -d %s\n",
			condition, quoteFish(helpFlagUsage))
	})
}

// fishFlag names a flag the way fish completes it: -s for one letter, -l for
// a long name.
func fishFlag(f *flag.Flag) string {
	if len(f.Name) == 1 {
		return "-s " + f.Name
	}
	return "-l " + f.Name
}

// quoteFish wraps text in a fish single-quoted string: inside those quotes
// only \\ and \' are escapes, and a newline would end the rule.
func quoteFish(text string) string {
	replacer := strings.NewReplacer("\\", "\\\\", "'", "\\'", "\n", " ")
	return "'" + replacer.Replace(text) + "'"
}
